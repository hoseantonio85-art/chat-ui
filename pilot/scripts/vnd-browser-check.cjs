const {chromium} = require(process.env.PLAYWRIGHT_MODULE || 'playwright');
const assert = require('node:assert/strict');
const path = require('node:path');
const output = path.join(process.env.RUNNER_TEMP || process.cwd(), 'qa-vnd');
require('node:fs').mkdirSync(output, {recursive:true});
(async () => {
  const browser = await chromium.launch();
  const page = await browser.newPage({viewport:{width:1728,height:1100}});
  page.setDefaultTimeout(15000);
  const origin = process.env.VND_BASE_URL || 'http://127.0.0.1:4410';
  const errors=[]; page.on('pageerror',e=>errors.push(e.message));
  const open = name => page.getByRole('button',{name,exact:true}).click();
  const closeChat = async () => {await open('Закрыть чат'); await page.getByRole('button',{name:'Закрыть чат',exact:true}).waitFor({state:'hidden'});};
  const welcome = async name => {await open(name); await page.getByText('Здравствуйте! Я помогу проверить ваш ВНД', {exact:false}).waitFor(); await closeChat();};
  try {
    await page.goto(origin+'/vnd/');
    await page.getByRole('button',{name:'Новости',exact:true}).waitFor();
    assert.equal(await page.getByRole('button',{name:'Закрыть чат',exact:true}).count(),0);
    await page.getByRole('textbox',{name:'Запрос помощнику'}).fill('Проверь мой регламент');
    await page.getByRole('textbox',{name:'Запрос помощнику'}).press('Enter');
    await page.getByText('Проверь мой регламент',{exact:true}).waitFor();
    const chatBox=await page.locator('[class*="_chat_"]').first().boundingBox();
    assert.ok(chatBox && Math.abs(chatBox.x-(1728-chatBox.width)/2)<5 && chatBox.width>1200 && chatBox.height>900,JSON.stringify(chatBox));
    const overlay=page.getByRole('dialog',{name:'Чат Норма',exact:true});
    assert.equal(await overlay.evaluate(el=>getComputedStyle(el).backgroundColor),'rgba(36, 40, 43, 0.56)');
    await page.screenshot({path:path.join(output,'centered-chat.png')});
    await closeChat();
    await page.getByRole('textbox',{name:'Запрос помощнику'}).click(); await closeChat();
    await open('Открыть чат'); await closeChat();
    await welcome('Проверить стандарты');
    await open('Новости'); await page.getByRole('dialog',{name:'Новости'}).waitFor();
    await page.keyboard.press('Escape'); await page.getByRole('dialog',{name:'Новости'}).waitFor({state:'hidden'});
    await open('Новости'); await open('Закрыть новости');
    await open('Новости'); await page.locator('.vnd-news-overlay').click({position:{x:10,y:10}});
    await page.getByRole('dialog',{name:'Новости'}).waitFor({state:'hidden'});
    await open('Новости'); await open('Проверка ВНД — перейти в базу знаний');
    await welcome('Поехали!'); await welcome('Проверить ВНД');
    await open('Открыть чат Норма');
    assert.equal(await page.getByText('Здравствуйте! Я помогу проверить ваш ВНД',{exact:false}).count(),0);
    await page.locator('textarea').fill('Проверь мой ВНД');
    await page.locator('textarea').press('Enter');
    await page.getByText('Проверь мой ВНД',{exact:true}).waitFor();
    await closeChat(); await open('Главная'); await open('База знаний');
    await page.screenshot({path:path.join(output,'knowledge.png'),fullPage:true});
    await open('Главная'); await page.screenshot({path:path.join(output,'home.png'),fullPage:true});
    await page.goto(origin+'/vnd/#knowledge');
    await open('Добавить документы в Стандарты');
    const upload=page.getByRole('dialog',{name:'Загрузка документов',exact:true});
    await upload.getByRole('button',{name:'Проверить ВНД',exact:true}).click();
    await page.getByText('Здравствуйте! Я помогу проверить ваш ВНД',{exact:false}).waitFor(); await closeChat();
    const uploadAndReview=async()=>{
      await open('Добавить документы в Стандарты');
      await upload.locator('input[type=file]').setInputFiles({name:'Проверенный регламент.docx',mimeType:'application/vnd.openxmlformats-officedocument.wordprocessingml.document',buffer:Buffer.from('Demo document')});
      await page.screenshot({path:path.join(output,'upload-documents.png')});
      await upload.getByRole('button',{name:'Отправить на проверку',exact:true}).click();
      await upload.waitFor({state:'hidden'});
      await page.locator('textarea').fill('1');await page.locator('textarea').press('Enter');
    };
    await uploadAndReview();
    await page.getByText('В документе выявлены отклонения от групповых требований.',{exact:false}).waitFor();await closeChat();
    await page.goto(origin+'/vnd/?review=clean#knowledge');
    await uploadAndReview();
    await page.getByText('Отклонений от выбранного группового стандарта не найдено.',{exact:false}).waitFor();
    await page.getByText('Сохранить актуальный ВНД в базе знаний, в папке «Стандарты»?',{exact:true}).waitFor();
    await page.screenshot({path:path.join(output,'clean-result.png')});
    await page.locator('textarea').fill('Да');await page.locator('textarea').press('Enter');
    await page.getByText('Сохранил «Проверенный регламент.docx» в базу знаний, в папку «Стандарты».',{exact:true}).waitFor();
    await page.screenshot({path:path.join(output,'saved-to-standards.png')});
    await closeChat();
    await page.goto(origin+'/');
    await page.getByRole('button',{name:'Закрыть чат',exact:true}).waitFor();
    await page.goto(origin+'/scenario-map/');
    await page.locator('#root').filter({hasText:/ВНД/}).waitFor();
    await page.screenshot({path:path.join(output,'scenario-map.png'),fullPage:true});
    await page.goto(origin+'/scenario-map/?scenario=vnd-to-be&step=vnd-to-be.standard&view=screens');
    const branches=page.getByRole('group',{name:'Варианты продолжения ВНД',exact:true});
    await branches.getByRole('button',{name:'Есть отклонения',exact:true}).waitFor();
    await branches.getByRole('button',{name:'Отклонений нет',exact:true}).click();
    assert.ok(page.url().includes('step=vnd-to-be.clean'));
    await page.getByRole('button',{name:'Открыть 100%',exact:true}).click();
    const live=page.frameLocator('.screen-modal iframe');
    await live.getByText('Сохранить актуальный ВНД в базе знаний, в папке «Стандарты»?',{exact:true}).waitFor();
    assert.equal(await live.getByText('В документе выявлены отклонения',{exact:false}).count(),0);
    await page.getByRole('button',{name:'Закрыть просмотр',exact:true}).click();
    await branches.getByRole('button',{name:'Исходный файл сохранён',exact:true}).click();
    await page.getByRole('button',{name:'Открыть 100%',exact:true}).click();
    await live.getByText('Сохранил «Регламент управления операционными рисками.docx» в базу знаний, в папку «Стандарты».',{exact:true}).waitFor();
    await page.getByRole('button',{name:'Следующий экран',exact:true}).isDisabled().then(disabled=>assert.equal(disabled,true));
    await page.getByRole('button',{name:'Закрыть просмотр',exact:true}).click();
    await page.screenshot({path:path.join(output,'vnd-to-be-branches-map.png'),fullPage:true});
    await page.waitForFunction(()=>Array.from(document.images).every(img=>img.complete));
    const broken=await page.locator('img').evaluateAll(images=>images.filter(img=>!img.complete || !img.naturalWidth).map(img=>img.src));
    assert.deepEqual(broken,[]);
    assert.deepEqual(errors,[]);
    console.log('VND entries, dismissal, supplied query, root and scenario map passed.');
  } finally {await browser.close();}
})().catch(e=>{console.error(e);process.exitCode=1;});
